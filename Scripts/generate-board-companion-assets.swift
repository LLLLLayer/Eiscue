bool companion_bitmap_decode_row(const companion_bitmap *bitmap,uint16_t y,
    uint16_t *destination,size_t max_pixels) {
    if(!bitmap || !destination || !bitmap->data || !bitmap->row_offsets ||
       y >= bitmap->height || !bitmap->width || max_pixels < bitmap->width) return false;
    uint32_t offset=bitmap->row_offsets[y],end=bitmap->row_offsets[y+1];
    if(offset > end || end > bitmap->data_length) return false;
    uint8_t *output=(uint8_t *)destination;
    size_t written=0;
    while(offset < end) {
        uint8_t header=bitmap->data[offset++];
        size_t count=(header & 127)+1,payload=(header & 128) ? 2 : count*2;
        if(count > bitmap->width-written || payload > end-offset) return false;
        for(size_t pixel=0;pixel<count;pixel++) {
            size_t source=offset+((header & 128) ? 0 : pixel*2);
            output[(written+pixel)*2]=bitmap->data[source];
            output[(written+pixel)*2+1]=bitmap->data[source+1];
        }
        written+=count; offset+=(uint32_t)payload;
    }
    return written == bitmap->width;
}

