func context(width: Int, height: Int) throws -> CGContext {
    guard let value = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8,
        bytesPerRow: width * 4, space: colorSpace,
        bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue | CGBitmapInfo.byteOrder32Big.rawValue)
    else { throw AssetError.invalid("Cannot create RGB bitmap") }
    value.setFillColor(background); value.fill(CGRect(x: 0, y: 0, width: width, height: height))
    value.interpolationQuality = .high
    return value
}

func pack(_ row: ArraySlice<UInt16>) -> [UInt8] {
    let values = Array(row)
    var bytes: [UInt8] = [], index = 0
    func append(_ value: UInt16) { bytes += [UInt8(value >> 8), UInt8(value & 255)] }
    func run(_ start: Int) -> Int {
        var count = 1
        while start + count < values.count && count < 128 && values[start + count] == values[start] { count += 1 }
        return count
    }
    while index < values.count {
        let count = run(index)
        if count >= 2 {
            bytes.append(0x80 | UInt8(count - 1)); append(values[index]); index += count
        } else {
            let first = index; index += 1
            while index < values.count && index - first < 128 && run(index) < 2 { index += 1 }
            bytes.append(UInt8(index - first - 1))
            for value in values[first..<index] { append(value) }
        }
    }
    return bytes
}

func unpack(_ bytes: ArraySlice<UInt8>, width: Int) throws -> [UInt16] {
    let data = Array(bytes)
    var pixels: [UInt16] = [], index = 0
    while index < data.count {
        let header = data[index]; index += 1
        let count = Int(header & 127) + 1
        let payload = header & 128 == 0 ? count * 2 : 2
        guard index + payload <= data.count, pixels.count + count <= width else {
            throw AssetError.invalid("Invalid compressed row")
        }
        for pixel in 0..<count {
            let offset = index + (header & 128 == 0 ? pixel * 2 : 0)
            pixels.append(UInt16(data[offset]) << 8 | UInt16(data[offset + 1]))
        }
        index += payload
    }
    guard pixels.count == width else { throw AssetError.invalid("Truncated row") }
    return pixels
}

func bitmap(_ name: String, context: CGContext) throws -> Bitmap {
    guard let image = context.makeImage(), let address = context.data else { throw AssetError.invalid(name) }
    let rgba = address.assumingMemoryBound(to: UInt8.self)
    var pixels: [UInt16] = [], bytes: [UInt8] = [], offsets: [UInt32] = [0]
    for y in 0..<context.height {
        for x in 0..<context.width {
            let offset = y * context.bytesPerRow + x * 4
            pixels.append(UInt16(rgba[offset] >> 3) << 11 | UInt16(rgba[offset + 1] >> 2) << 5 | UInt16(rgba[offset + 2] >> 3))
        }
        let row = pixels[(y * context.width)..<((y + 1) * context.width)]
        let encoded = pack(row)
        guard try unpack(encoded[...], width: context.width) == Array(row) else {
            throw AssetError.invalid("Row round-trip failed for \(name)")
        }
        bytes += encoded; offsets.append(UInt32(bytes.count))
    }
    return Bitmap(name: name, width: context.width, height: context.height,
        image: image, pixels: pixels, bytes: bytes, offsets: offsets)
}

func textBitmap(_ text: String, name: String, layout: String, fontName: String) throws -> Bitmap {
    let width = layout == "digit" ? 14 : 216
    let height: Int, size: CGFloat
    switch layout {
    case "title": height = 44; size = 20
    case "hint": height = 28; size = 15
    case "caption": height = 24; size = 14
    case "digit": height = 20; size = 18
    default: throw AssetError.invalid("Unknown layout \(layout)")
    }
    let font = CTFontCreateWithName(fontName as CFString, size, nil)
    guard CTFontCopyPostScriptName(font) as String == fontName else {
        throw AssetError.invalid("Required font is missing: \(fontName)")
    }
    let attributes: [NSAttributedString.Key: Any] = [
        NSAttributedString.Key(kCTFontAttributeName as String): font,
        NSAttributedString.Key(kCTForegroundColorAttributeName as String): foreground
    ]
    let attributed = NSAttributedString(string: text, attributes: attributes)
    let typesetter = CTTypesetterCreateWithAttributedString(attributed)
    var start = 0, lines: [CTLine] = []
    while start < attributed.length {
        let length = CTTypesetterSuggestLineBreak(typesetter, start, Double(width - 4))
        guard length > 0 else { throw AssetError.invalid("Cannot fit \(name)") }
        lines.append(CTTypesetterCreateLine(typesetter, CFRange(location: start, length: length)))
        start += length
    }
    let lineHeight: CGFloat = layout == "title" ? 22 : CGFloat(height)
    guard !lines.isEmpty, CGFloat(lines.count) * lineHeight <= CGFloat(height) else {
        throw AssetError.invalid("Too many lines in \(name): \(text)")
    }
    let canvas = try context(width: width, height: height)
    // Grayscale antialiasing stays legible on RGB565 without LCD subpixel color fringes.
    canvas.setShouldAntialias(true); canvas.setShouldSmoothFonts(false)
    let top = (CGFloat(height) - CGFloat(lines.count) * lineHeight) / 2
    for (index, line) in lines.enumerated() {
        let bounds = CTLineGetBoundsWithOptions(line, [.useGlyphPathBounds])
        let centerY = CGFloat(height) - top - CGFloat(index) * lineHeight - lineHeight / 2
        canvas.textPosition = CGPoint(x: (CGFloat(width) - bounds.width) / 2 - bounds.minX,
            y: centerY - bounds.midY)
        CTLineDraw(line, canvas)
    }
    return try bitmap(name, context: canvas)
}

func cArray<T>(_ values: [T], format: (T) -> String, count: Int) -> String {
    stride(from: 0, to: values.count, by: count).map { offset in
        "    " + values[offset..<min(offset + count, values.count)].map(format).joined(separator: ",")
    }.joined(separator: ",\n")
}
func cBitmap(_ bitmap: Bitmap) -> String {
    """
    static const uint8_t \(bitmap.name)_data[] = {
    \(cArray(bitmap.bytes, format: { String(format: "0x%02X", $0) }, count: 24))
    };
    static const uint32_t \(bitmap.name)_rows[] = {
    \(cArray(bitmap.offsets, format: { String($0) }, count: 16))
    };
    static const companion_bitmap \(bitmap.name) = {
        \(bitmap.width),\(bitmap.height),\(bitmap.name)_data,sizeof(\(bitmap.name)_data),\(bitmap.name)_rows
    };

    """
}
func sha256(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }
func png(_ image: CGImage, at url: URL) throws {
    guard let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil)
    else { throw AssetError.invalid("Cannot create \(url.path)") }
    CGImageDestinationAddImage(destination, image, nil)
    guard CGImageDestinationFinalize(destination) else { throw AssetError.invalid("Cannot write \(url.path)") }
}
func write(_ content: String, at url: URL) throws {
    let data = Data(content.utf8)
    if check {
        guard try Data(contentsOf: url) == data else { throw AssetError.invalid("Regenerate \(url.path)") }
    } else { try data.write(to: url, options: .atomic) }
}

